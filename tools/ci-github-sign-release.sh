#!/usr/bin/env bash
# Create the permanent publishing key ON GITHUB ACTIONS, then reuse its encrypted
# escrow on every subsequent build. The plaintext signing key never enters Git.
set -euo pipefail
set +x
umask 077
cd "$(dirname "$0")/.."

if [[ "$GITHUB_ACTIONS" != "true" ]]; then
  echo "::error::This automated publishing key must be created/used by GitHub Actions." >&2
  exit 1
fi
if [[ -z "$DSHA_SIGNING_MASTER_PASSWORD" || ${#DSHA_SIGNING_MASTER_PASSWORD} -lt 32 ]]; then
  echo "::error::Set one strong (32+ character) Actions secret: DSHA_SIGNING_MASTER_PASSWORD" >&2
  exit 1
fi
if [[ "$GITHUB_REF_NAME" != "upgrade/dsh-0.2.1-rc.2" ]]; then
  echo "::error::Refusing to publish from an untrusted branch." >&2
  exit 1
fi

tool_dir="$ANDROID_HOME/build-tools/$(python3 tools/ci-toolchain.py --field buildTools)"
aapt="$tool_dir/aapt"
apksigner="$tool_dir/apksigner"
zipalign="$tool_dir/zipalign"
for tool in keytool gpg git python3 sha256sum; do command -v "$tool" >/dev/null; done
for tool in "$aapt" "$apksigner" "$zipalign"; do test -x "$tool"; done

unsigned="unsigned-release/app-standard-release-unsigned.apk"
test -s "$unsigned"
scratch="$(mktemp -d "$RUNNER_TEMP/dsha-sign-XXXXXXXX")"
trap 'rm -rf "$scratch"' EXIT
keystore="$scratch/github-dsha-release.p12"
aligned="$scratch/standard-aligned.apk"
cipher="ci/github-signing/dsha-permanent-release.p12.gpg"
marker="ci/github-signing/certificate.sha256"
identity="ci/release-identity.json"
outdir="verified-signed-release"
output="$outdir/dsha-0.2.30.apk"
mkdir -p "$(dirname "$cipher")" "$outdir"
bootstrap=0

# Serialize signing jobs and load the durable identity from the current branch,
# even when this workflow started before another run escrowed its first key.
git fetch origin "$GITHUB_REF_NAME"
for path in "$identity" "$cipher" "$marker"; do
  if git cat-file -e "origin/$GITHUB_REF_NAME:$path" 2>/dev/null; then
    git show "origin/$GITHUB_REF_NAME:$path" > "$path"
  elif [[ "$path" != "$identity" ]]; then
    rm -f -- "$path"
  else
    echo "::error::Publishing identity missing from branch" >&2; exit 1
  fi
done
signing_mode="$(python3 tools/github-signing-state.py)"
if [[ "$signing_mode" == "reuse" ]]; then
  echo "Decrypting the SAME permanent key generated by earlier GitHub Actions."
  printf '%s' "$DSHA_SIGNING_MASTER_PASSWORD" |
    gpg --quiet --batch --yes --pinentry-mode loopback --passphrase-fd 0 \
      --output "$keystore" --decrypt "$cipher"
  test -s "$keystore"
else
  echo "First secure GitHub Actions publish: GENERATING NEW permanent RSA-4096 release key."
  bootstrap=1
  keytool -genkeypair -noprompt \
    -alias dsha-publish -keyalg RSA -keysize 4096 -sigalg SHA256withRSA \
    -validity 36500 -dname "CN=DSHA Release, OU=Android, O=DSHA, C=US" \
    -storetype PKCS12 -keystore "$keystore" \
    -storepass:env DSHA_SIGNING_MASTER_PASSWORD \
    -keypass:env DSHA_SIGNING_MASTER_PASSWORD
  printf '%s' "$DSHA_SIGNING_MASTER_PASSWORD" |
    gpg --quiet --batch --yes --pinentry-mode loopback --passphrase-fd 0 \
      --symmetric --cipher-algo AES256 --s2k-mode 3 --s2k-digest-algo SHA512 \
      --s2k-count 65011712 --output "$cipher" "$keystore"
  test -s "$cipher"
  printf '%s' "$DSHA_SIGNING_MASTER_PASSWORD" |
    gpg --quiet --batch --yes --pinentry-mode loopback --passphrase-fd 0 \
      --output "$scratch/roundtrip.p12" --decrypt "$cipher"
  cmp "$keystore" "$scratch/roundtrip.p12"
fi

certificate="$(
  keytool -exportcert -alias dsha-publish -keystore "$keystore" \
    -storetype PKCS12 -storepass:env DSHA_SIGNING_MASTER_PASSWORD |
    sha256sum | awk '{print $1}'
)"
if [[ ! "$certificate" =~ ^[a-f0-9]{64}$ ]]; then
  echo "::error::Cannot read APK publishing certificate" >&2
  exit 1
fi

if [[ "$bootstrap" == "1" ]]; then
  # The pre-existing ChatGPT-signed cert is NOT reused. The new public identity
  # is adopted exactly once along with an encrypted copy of the GitHub key.
  # Activate only after generating and round-trip checking the encrypted key.
  # The helper checks the pre-generation identity before cipher publication.
  mv "$cipher" "$scratch/escrow.gpg"
  python3 tools/github-signing-state.py activate "$certificate"
  mv "$scratch/escrow.gpg" "$cipher"
else
  recorded="$(cat "$marker")"
  expected="$(python3 -c 'import json;print(json.load(open("ci/release-identity.json"))["certificateSha256"])')"
  if [[ "$certificate" != "$recorded" || "$certificate" != "$expected" ]]; then
    echo "::error::Recovered signing key DOES NOT match permanent GitHub certificate." >&2
    exit 1
  fi
fi

"$zipalign" -P 16 -f 4 "$unsigned" "$aligned"
"$apksigner" sign --ks "$keystore" --ks-type PKCS12 --ks-key-alias dsha-publish \
  --ks-pass env:DSHA_SIGNING_MASTER_PASSWORD \
  --key-pass env:DSHA_SIGNING_MASTER_PASSWORD \
  --v1-signing-enabled true --v2-signing-enabled true --v3-signing-enabled true \
  --out "$output" "$aligned"
python3 tools/verify-official-apk.py --apk "$output" --flavor standard \
  --aapt "$aapt" --apksigner "$apksigner"
python3 tools/verify-apk-runtime-contract.py "$output"
python3 - "$unsigned" "$output" <<'PY'
import sys,zipfile
with zipfile.ZipFile(sys.argv[1]) as before,zipfile.ZipFile(sys.argv[2]) as after:
    assert after.testzip() is None
    names=('AndroidManifest.xml', 'assets/dsh-runtime.bin',
           'assets/offline-rootfs.bin', 'assets/runtime-descriptor.json')
    for name in names:
        a,b=before.getinfo(name),after.getinfo(name)
        if (a.file_size,a.CRC)!=(b.file_size,b.CRC):
            raise SystemExit('SIGNED_APK_CONTENT_DRIFT:'+name)
print('GITHUB_SIGNED_APK_CONTENT_VERIFIED')
PY

# Escrow FIRST so we do not publish an APK whose signing key cannot be reused.
if [[ "$bootstrap" == "1" ]]; then
  git add -- "$cipher" "$marker" "$identity"
  git -c user.name='github-actions[bot]' \
      -c user.email='41898282+github-actions[bot]@users.noreply.github.com' \
      commit -m 'Store GitHub-generated DSHA signing identity and encrypted escrow'
  # The branch may advance while this long build is running (for example,
  # documentation-only commits). Rebase the escrow-only commit safely.
  git fetch origin "$GITHUB_REF_NAME"
  git rebase "origin/$GITHUB_REF_NAME"
  git push origin "HEAD:$GITHUB_REF_NAME"
  # A concurrent identity edit must never publish an APK with a different key.
  python3 tools/github-signing-state.py
  test "$(cat "$marker")" = "$certificate"
  python3 tools/verify-official-apk.py --apk "$output" --flavor standard \
    --aapt "$aapt" --apksigner "$apksigner"
  echo "GITHUB_SIGNING_KEY_SECURELY_ESCROWED"
fi

(cd "$outdir" && sha256sum dsha-0.2.30.apk > dsha-0.2.30.apk.sha256)
{
  echo "## GitHub-generated, permanently signed DSHA v180"
  echo "Signing certificate SHA-256: \`$certificate\`"
  echo "GitHub Actions generated and securely escrowed this key; no ChatGPT-cloud keystore is used."
  echo "Download the DSHA-v180-GITHUB-KEY-SIGNED-STANDARD-APK artifact as a ZIP."
} >> "$GITHUB_STEP_SUMMARY"
echo "GITHUB_PERMANENTLY_SIGNED_RELEASE_READY $certificate"
